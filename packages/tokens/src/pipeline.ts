/**
 * Token pipeline (T0401, ADR-004): validate → check semantic roles →
 * generate derived exports (CSS custom properties, TS constants). Exports
 * are regenerable; the drift gate (G12) compares committed exports against
 * regeneration. Gate verdicts for G1 and G12 are emitted here.
 */
import { existsSync, readFileSync } from 'node:fs';
import { missingSemanticRoles, flattenTokens, type DtcgGroup, type DtcgToken } from '@sus/schemas';

export interface TokenPipelineResult {
  valid: boolean;
  detail: string[];
  tokens: Map<string, DtcgToken>;
}

export function loadTokens(tokensPath: string): TokenPipelineResult {
  const detail: string[] = [];
  if (!existsSync(tokensPath)) {
    return {
      valid: false,
      detail: ['no .sus/tokens.json found — G1 cannot be satisfied without a token contract'],
      tokens: new Map(),
    };
  }
  let file: Record<string, unknown>;
  try {
    file = JSON.parse(readFileSync(tokensPath, 'utf8')) as Record<string, unknown>;
  } catch (e) {
    return { valid: false, detail: [`tokens file unparseable: ${String(e)}`], tokens: new Map() };
  }
  const missing = missingSemanticRoles(file);
  if (missing.length > 0) {
    detail.push(`missing required semantic roles: ${missing.join(', ')}`);
  }
  return { valid: missing.length === 0, detail, tokens: flattenTokens(file) };
}

/** CSS custom properties: --sus-<path> with dot→dash conversion. */
export function generateCss(tokens: Map<string, DtcgToken>): string {
  const lines = [':root {'];
  for (const [path, token] of [...tokens.entries()].sort()) {
    lines.push(`  --sus-${path.replace(/\./g, '-')}: ${String(token.$value)};`);
  }
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/** TS constants: SUS_TOKENS record keyed by semantic path. */
export function generateTs(tokens: Map<string, DtcgToken>): string {
  const entries = [...tokens.entries()].sort().map(([path, t]) => {
    const key = path
      .replace(/\.([a-z])/g, (_, c: string) => c.toUpperCase())
      .replace(/\.([A-Z])/g, (_, c: string) => c.toUpperCase())
      .split('.')
      .join('');
    const v = typeof t.$value === 'number' ? String(t.$value) : JSON.stringify(t.$value);
    return `  ${key}: ${v},`;
  });
  return `/** Generated by @sus/tokens — do not edit; regenerate instead (ADR-004/G12). */\nexport const SUS_TOKENS = {\n${entries.join('\n')}\n} as const;\n`;
}

export type GateStatus = 'pass' | 'fail' | 'not-run';
export interface GateResult {
  gate: 'G1' | 'G12';
  status: GateStatus;
  detail: string[];
}

/**
 * G12 (contract drift): committed exports must byte-match regeneration.
 * @param committedCss/committedTs content of the committed export files.
 */
export function evaluateG12(
  tokensPath: string,
  committedCss: string | null,
  committedTs: string | null,
): GateResult {
  const pipeline = loadTokens(tokensPath);
  if (!pipeline.valid) {
    return { gate: 'G12', status: 'fail', detail: pipeline.detail };
  }
  const detail: string[] = [];
  let failed = false;
  const css = generateCss(pipeline.tokens);
  const ts = generateTs(pipeline.tokens);
  if (committedCss === null) {
    failed = true;
    detail.push(
      'no committed CSS export found — regenerate and commit (pipeline output is authoritative)',
    );
  } else if (committedCss !== css) {
    failed = true;
    detail.push('committed CSS export diverges from regeneration — run the token pipeline');
  }
  if (committedTs === null) {
    failed = true;
    detail.push('no committed TS export found');
  } else if (committedTs !== ts) {
    failed = true;
    detail.push('committed TS export diverges from regeneration — run the token pipeline');
  }
  if (!failed) detail.push('committed exports match regeneration (no drift)');
  return { gate: 'G12', status: failed ? 'fail' : 'pass', detail };
}

/**
 * G1 (token-only styling): a token contract must exist and carry the
 * semantic roles; the raw-value ban itself is enforced by the eslint rule
 * (scripts/lint-rules/no-raw-style-values.mjs, extended to px in M4 follow-up).
 */
export function evaluateG1(tokensPath: string): GateResult {
  const pipeline = loadTokens(tokensPath);
  return {
    gate: 'G1',
    status: pipeline.valid ? 'pass' : 'fail',
    detail: pipeline.valid
      ? [
          `token contract valid with ${pipeline.tokens.size} tokens; raw-value ban enforced by eslint rule`,
        ]
      : pipeline.detail,
  };
}

