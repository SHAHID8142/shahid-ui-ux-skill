/**
 * T0905 tests — the compatibility record binds evidence to artifacts.
 *
 * The behaviour that matters: when the artifact changes, old smoke evidence is
 * stale, and a stale row is downgraded rather than kept. Also that the docs page
 * and the CLI render the same generated record, so neither can drift from it.
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  buildCompatibility,
  effectiveTier,
  evidenceState,
  renderSupportMatrix,
  statusText,
  type CompatibilityDocument,
  type HostAdapter,
} from '../src/index.js';

const ARTIFACT = { id: 'sus-adapters', sha256: 'a'.repeat(64) };
const ENV = {
  hostVersion: '1.2.3',
  browser: 'Chrome 141 headless',
  framework: 'next 15.5.4',
  os: 'darwin 25.1.0',
};

const adapter = (overrides: Partial<HostAdapter> = {}): HostAdapter => ({
  id: 'demo-host',
  installMethod: 'generated entry',
  smokeTest: 'node scripts/coord/smoke-host.mjs',
  capabilities: {
    skillTriggering: 'verified',
    cliExecution: 'verified',
    jitReferenceLoading: 'verified',
    liveStudio: 'verified',
  },
  evidence: 'see receipt',
  ...overrides,
});

const build = (
  overrides: {
    evidence?: { ref: string; artifactSha256: string; recordedAt: string } | null;
    adapters?: HostAdapter[];
  } = {},
) =>
  buildCompatibility({
    adapters: overrides.adapters ?? [adapter()],
    artifacts: { 'demo-host': ARTIFACT },
    environments: { 'demo-host': ENV },
    evidence:
      overrides.evidence === undefined
        ? {
            'demo-host': {
              ref: 'evals/host-smoke/demo-host-abc.json',
              artifactSha256: ARTIFACT.sha256,
              recordedAt: '2026-11-15',
            },
          }
        : { 'demo-host': overrides.evidence },
  });

describe('evidence freshness is a hash comparison (T0905)', () => {
  it('missing when there is no evidence at all', () => {
    expect(evidenceState(null, ARTIFACT.sha256)).toBe('missing');
  });

  it('verified only when the hashes match exactly', () => {
    expect(
      evidenceState(
        { ref: 'x', artifactSha256: ARTIFACT.sha256, recordedAt: '2026-11-15' },
        ARTIFACT.sha256,
      ),
    ).toBe('verified');
  });

  it('stale when the artifact changed after the run', () => {
    expect(
      evidenceState(
        { ref: 'x', artifactSha256: 'b'.repeat(64), recordedAt: '2026-11-14' },
        ARTIFACT.sha256,
      ),
    ).toBe('stale');
  });

  it('stale when the receipt predates artifact binding (empty hash)', () => {
    expect(
      evidenceState({ ref: 'x', artifactSha256: '', recordedAt: '2026-11-14' }, ARTIFACT.sha256),
    ).toBe('stale');
  });
});

describe('tier derivation and downgrade (T0905)', () => {
  it('a supported row with fresh evidence stays supported', () => {
    expect(effectiveTier('supported', 'verified')).toBe('supported');
  });

  it('a supported row with stale evidence is downgraded, never kept', () => {
    expect(effectiveTier('supported', 'stale')).toBe('experimental');
    expect(effectiveTier('supported', 'missing')).toBe('experimental');
  });

  it('downgrading never upgrades a row that was already lower', () => {
    expect(effectiveTier('experimental', 'stale')).toBe('experimental');
    expect(effectiveTier('unsupported', 'verified')).toBe('unsupported');
  });

  it('the document records both the derived and the effective tier', () => {
    const doc = build({
      evidence: { ref: 'x', artifactSha256: 'b'.repeat(64), recordedAt: '2026-11-14' },
    });
    expect(doc.rows[0]!.derivedTier).toBe('supported');
    expect(doc.rows[0]!.tier).toBe('experimental');
    expect(doc.rows[0]!.evidenceState).toBe('stale');
  });
});

describe('the record refuses to guess its inputs (T0905)', () => {
  it('refuses a host with no artifact binding', () => {
    expect(() =>
      buildCompatibility({
        adapters: [adapter()],
        artifacts: {},
        environments: { 'demo-host': ENV },
        evidence: {},
      }),
    ).toThrow(/no artifact binding/);
  });

  it('refuses a host with no environment facts', () => {
    expect(() =>
      buildCompatibility({
        adapters: [adapter()],
        artifacts: { 'demo-host': ARTIFACT },
        environments: {},
        evidence: {},
      }),
    ).toThrow(/no environment facts/);
  });
});

describe('rendering is generated, not authored (T0905)', () => {
  it('the docs page carries the do-not-edit header and the environment', () => {
    const markdown = renderSupportMatrix(build());
    expect(markdown).toContain('GENERATED by scripts/generate-support.mjs — do not edit by hand');
    expect(markdown).toContain('Chrome 141 headless');
    expect(markdown).toContain('next 15.5.4');
    expect(markdown).toContain('sus-adapters@aaaaaaaaaaaa');
  });

  it('stale rows say so in the table instead of reading as current', () => {
    const markdown = renderSupportMatrix(
      build({
        evidence: {
          ref: 'evals/host-smoke/old.json',
          artifactSha256: 'c'.repeat(64),
          recordedAt: '2026-11-01',
        },
      }),
    );
    expect(markdown).toContain('STALE');
    expect(markdown).toContain('tier downgraded');
  });

  it('the CLI status output flags stale evidence and separates derived from effective tier', () => {
    const doc = build({
      evidence: { ref: 'x', artifactSha256: 'b'.repeat(64), recordedAt: '2026-11-14' },
    });
    const text = statusText(doc);
    expect(text).toContain('evidence=stale');
    expect(text).toContain('derived=supported');
    expect(text).toContain('re-run the smoke test');
  });

  it('matches the committed generation snapshot', () => {
    expect(renderSupportMatrix(build())).toMatchSnapshot();
  });
});

describe('the committed docs agree with the committed record (T0905)', () => {
  const root = join(__dirname, '..', '..', '..');
  const jsonPath = join(root, 'docs', 'compatibility.json');
  const mdPath = join(root, 'docs', 'SUPPORT_MATRIX.md');

  it('both generated files exist', () => {
    expect(existsSync(jsonPath)).toBe(true);
    expect(existsSync(mdPath)).toBe(true);
  });

  it('the markdown lists exactly the hosts in the JSON, with the same tiers', () => {
    const doc = JSON.parse(readFileSync(jsonPath, 'utf8')) as CompatibilityDocument;
    const markdown = readFileSync(mdPath, 'utf8');
    expect(doc.schema).toBe('sus.compatibility');
    for (const row of doc.rows) {
      expect(markdown).toContain(`| ${row.host} | ${row.tier} |`);
    }
    // every host mentioned in the table body is also in the record
    const tableHosts = markdown
      .split('\n')
      .filter(
        (line) => line.startsWith('| ') && !line.startsWith('| Host') && !line.startsWith('| ---'),
      )
      .map((line) => line.split('|')[1]?.trim())
      .filter((value): value is string => Boolean(value));
    expect(tableHosts.sort()).toEqual(doc.rows.map((row) => row.host).sort());
  });
});
